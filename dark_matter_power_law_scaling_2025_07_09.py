import matplotlib.pyplot as plt
import numpy as np
import seaborn as sns
from typing_extensions import DefaultDict

sns.set_style("whitegrid")

compute = np.power(10, np.linspace(16, 30, 100))

# Function: Cross entropy loss = \sum_i a_i C^{-b_i} + c
# Note: The "standard" functional form has only one scaling term: Loss = a C^{-b} + c

# Approximate range: [10, 1000]
a_array = np.array(
    [
        # 10.0,
        10.0,
        10.0,
        500.0,
    ],
    # dtype=np.float128
).reshape(-1, 1)

# Approximate range: [0.09, 0.14]
b_array = np.array(
    [
        # 0.04,
        0.07,
        0.10,
        0.14,
    ],
    # dtype=np.float128,
).reshape(-1, 1)

# Approximate range: [0.1, 1.0]
c_array = np.array(
    [
        0.0,
        # 0.0,
    ],
    # dtype=np.float128,
).reshape(-1, 1)

assert b_array.shape[0] == a_array.shape[0]
num_terms = a_array.shape[0]

plt.close()
fig, axes = plt.subplots(figsize=(10, 5), ncols=2)
for term_idx in range(1, 1+num_terms):  # 1-based indexing.

  probs_correct = np.exp(
      -np.sum(                                 # Shape: (compute,)
          np.multiply(
              a_array[:term_idx],                         # Shape: (number of terms, 1)
              np.power(compute, -b_array[:term_idx]),          # Shape
          ),
          axis=0,
      )
      -np.sum(c_array)
  )
  neg_log_probs_correct = -np.log(probs_correct)

  axes[0].plot(compute, probs_correct, label=f"{term_idx} Terms")
  axes[1].plot(compute, neg_log_probs_correct, label=f"{term_idx} Terms")

axes[0].set_ylabel(r"$p_{\theta}(x)$")
axes[0].set_xlabel("FLOP")
axes[0].set_xscale("log")
axes[0].set_yscale("log")
axes[0].set_ylim(None, 1.0)
axes[0].legend()
axes[1].set_ylabel(r"$\mathcal{L}(\theta) := -\log p_{\theta}(x)$")
axes[1].set_xlabel("FLOP")
axes[1].set_xscale("log")
axes[1].set_yscale("log")
axes[1].legend()
fig.suptitle(f"a={a_array[:, 0].tolist()}\nb={b_array[:, 0].tolist()}\nc={c_array[:, 0].tolist()}")
plt.tight_layout()

