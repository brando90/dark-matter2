"""Write results/summary.md (the readable tables) and results/manifest.txt (sha256 of every result file).

    python summarize.py         # after dm2.py
"""
import hashlib
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")


def fmt(x, nd=3):
    if isinstance(x, str):
        return x
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "-"
    if abs(x) >= 1e4 or (0 < abs(x) < 1e-3):
        return f"{x:.2e}"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def md(df, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(fmt(r[c]) for c in cols) + " |")
    return "\n".join(out)


def verdict(r):
    if r.get("testable", 1) == 0:
        return "untestable"
    if r.shows_term:
        return "SECOND TERM"
    if r.detect_primary:
        return "primary only (boot z<2)"
    return "none"


def main():
    A = pd.read_csv(os.path.join(RES, "tableA.csv"))
    B = pd.read_csv(os.path.join(RES, "tableB.csv"))
    S = pd.read_csv(os.path.join(RES, "seed_sigma.csv"))
    A["verdict"] = [verdict(r) for _, r in A.iterrows()]
    B["verdict"] = [verdict(r) for _, r in B.iterrows()]
    A["Nrange"] = [f"{a / 1e6:.0f}M-{b / 1e6:.0f}M" for a, b in zip(A.Nmin, A.Nmax)]
    A["fpos"] = [f"{int(p)}/{int(n)}" if np.isfinite(p) else "-" for p, n in zip(A.rev_pos, A.rev_n)]
    B["fpos"] = [f"{int(p)}/{int(n)}" if np.isfinite(p) else "-" for p, n in zip(B.rev_pos, B.rev_n)]
    L = ["# DM-2 results", "", "Generated by summarize.py from tableA.csv / tableB.csv. Rule: primary = Wald z > 2 and "
         "dBIC > 2; SECOND TERM = primary and bootstrap z > 2. B2 is the fast-term coefficient at N = 1M params "
         "(n = 1); fast share = B n^-beta / (A n^-alpha) at the smallest size.", ""]
    cols = ["curve", "how", "npts", "Nrange", "alpha1", "alpha2", "B2", "beta2", "z_wald", "dbic", "cond", "se_boot",
            "z_boot", "fast_share_at_Nmin", "sigma_resid", "ho_rmse1", "ho_rmse2", "rev_mean", "fpos", "verdict"]
    for sl, title in (("D=20N", "## A. N-only at D = 20N, total parameters"),
                      ("final", "## A'. N-only on the literal last-checkpoint loss (token-budget confounded), total parameters")):
        L += [title, "", md(A[(A.slice == sl) & (A["count"] == "N_total")], cols), ""]
    L += ["## H5. Same curves with non-embedding (and Chinchilla's reported) counts", ""]
    h = A[A["count"] != "N_total"]
    L += [md(h, ["curve", "slice", "count", "npts", "alpha1", "alpha2", "B2", "beta2", "z_wald", "dbic", "z_boot",
                 "ho_rmse1", "ho_rmse2", "rev_mean", "fpos", "verdict"]), ""]
    L += ["## B. Joint L = E + A N^-alpha + B N^-beta + G D^-gamma (annealed final points)", "",
          md(B, ["ladder", "count", "npts", "sizes", "alpha1", "gamma1", "alpha2", "B2", "beta2", "gamma2", "z_wald",
                 "dbic", "cond", "se_boot", "z_boot", "sigma_resid", "ho_rmse1", "ho_rmse2", "rev_mean", "fpos",
                 "verdict"]), ""]
    ex = os.path.join(RES, "tableB_explore.csv")
    if os.path.exists(ex):
        X = pd.read_csv(ex)
        X["verdict"] = [verdict(r) for _, r in X.iterrows()]
        X["fpos"] = [f"{int(p)}/{int(n)}" if np.isfinite(p) else "-" for p, n in zip(X.rev_pos, X.rev_n)]
        L += ["## B (post hoc). Joint fit on Porian tuned constant-LR curves, D/N = 2.5..320 (correlated points)", "",
              md(X, ["ladder", "count", "npts", "sizes", "alpha1", "gamma1", "alpha2", "B2", "beta2", "gamma2",
                     "z_wald", "dbic", "cond", "se_boot", "z_boot", "sigma_resid", "ho_rmse1", "ho_rmse2", "rev_mean",
                     "fpos", "verdict"]), ""]
    L += ["## Seed sigma (Porian seed runs, final loss)", "", md(S, ["dataset", "width", "N_total", "seeds", "tpp", "mean", "sd"]), "",
          f"Pooled rms seed sd: ~20 tok/param {np.sqrt((S[S.tpp < 50].sd ** 2).mean()):.4f}, "
          f"~200 tok/param {np.sqrt((S[S.tpp > 50].sd ** 2).mean()):.4f}", ""]
    dm = [c for c in A.columns if c.startswith("dm1_pow")]
    L += ["## Reading a null with DM-1 (matched cells: power of the primary rule)", "",
          md(A[(A["count"] == "N_total")], ["curve", "slice", "span_dec", "ppd", "sigma_resid", "dm1_window", "dm1_ppd",
                                            "dm1_sigma", "dm1_fpr"] + dm), ""]
    open(os.path.join(RES, "summary.md"), "w").write("\n".join(L))
    files = sorted(f for f in os.listdir(RES) if f.endswith((".csv", ".md", ".json")) and f != "manifest.txt")
    with open(os.path.join(RES, "manifest.txt"), "w") as fh:
        for f in files:
            fh.write(f"{hashlib.sha256(open(os.path.join(RES, f), 'rb').read()).hexdigest()} {f}\n")
    print(f"wrote summary.md and manifest.txt ({len(files)} files)")


if __name__ == "__main__":
    main()
