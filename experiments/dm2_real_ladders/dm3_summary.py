"""Write results/dm3_summary.md (DM-3 tables and the pre-registered verdict) from results/dm3_*.csv.

    python dm3_summary.py       # after dm3.py; then summarize.py (rehashes the manifest) and verify.py
"""
import os

import numpy as np
import pandas as pd

from summarize import fmt, md

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")


def verdict(a, k):
    """The addendum's decision rule, per dataset rows a (A3 test) and k (B3 test)."""
    acc = (not a.shows_term) and a.c1_ci_excludes_1 and abs(a.rev_mean_1term_c1) <= 0.05 and \
        ((not k.shows_term) or k.c_K2_ci_excludes_1)
    dm = a.shows_term and k.detect_primary
    return acc, dm


def main():
    P = pd.read_csv(os.path.join(RES, "dm3_profileA.csv"))
    T = pd.read_csv(os.path.join(RES, "dm3_tableA_at_c.csv"))
    A = pd.read_csv(os.path.join(RES, "dm3_testA.csv"))
    H = pd.read_csv(os.path.join(RES, "dm3_holdoutA.csv"))
    R = pd.read_csv(os.path.join(RES, "dm3_residualsA.csv"))
    K = pd.read_csv(os.path.join(RES, "dm3_testK.csv"))
    RK = pd.read_csv(os.path.join(RES, "dm3_reverseK.csv"))
    out = ["# DM-3 summary (generated by dm3_summary.py)", ""]
    out += ["## Verdict by the addendum's rule", ""]
    rows = []
    for ds in A.dataset:
        a, k = A[A.dataset == ds].iloc[0], K[K.dataset == ds].iloc[0]
        acc, dm = verdict(a, k)
        rows.append(dict(dataset=ds, A3_shows_term=int(a.shows_term), c1_CI_excludes_1=bool(a.c1_ci_excludes_1),
                         rev_mean_c1=a.rev_mean_1term_c1, K2_detect=int(k.detect_primary),
                         embedding_accounting=acc, dark_matter=dm))
    V = pd.DataFrame(rows)
    out.append(md(V, list(V.columns)))
    allacc, alldm = V.embedding_accounting.all(), V.dark_matter.all()
    out += ["", f"**Verdict: {'embedding accounting' if allacc else 'dark matter' if alldm else 'undetermined'}**", ""]
    out += ["## A3: c profiled, N-only at D = 20N (14 sizes)", ""]
    cols = ["dataset", "c1", "c1_ci_set", "c1_boot_lo", "c1_boot_hi", "sigma1_free", "c2", "c2_ci_set", "sigma2_free",
            "dbic_free", "B_c2", "beta_c2", "z_wald_c2", "z_boot", "boot_frac_pos", "c2_boot_median",
            "detect_primary", "shows_term"]
    out.append(md(A, cols))
    out += ["", "Fixed-c fits (k = 3 vs 5; dBIC at fixed c):", ""]
    out.append(md(T, ["dataset", "at", "c", "alpha1", "sigma1", "B2", "beta2", "alpha2", "sigma2", "z_wald", "dbic",
                      "fast_share_at_Nmin"]))
    out += ["", "Profile (every 0.1 in c):", ""]
    g = P[np.isclose((P.c * 10) % 1, 0) | np.isclose((P.c * 10) % 1, 1)]
    out.append(md(g, ["dataset", "c", "rss1", "alpha1", "E1", "rss2", "B2", "beta2", "z_wald"]))
    ph = [c for c in A.columns if c.startswith("posthoc_")]
    out += ["", "Post hoc: 1-term RSS past the grid (c > 2, and N = N_emb alone):", ""]
    out.append(md(A, ["dataset", "rss1_free"] + ph))
    out += ["", "## A3 hold-out (fit the smaller 10, predict the largest 4): RMSE", ""]
    out.append(md(H, list(H.columns)))
    out += ["", "## A3 residuals per size (observed - predicted; rev_* = fitted on the 5 sizes >= 100M)", ""]
    out.append(md(R, ["dataset", "N_total", "emb_share", "big", "rev_1term_c1", "rev_1term_strict", "rev_1term_c=1",
                      "full_1term_c1", "full_2term_c2"]))
    out += ["", "## B3: Kaplan-style joint law on the constant-LR curve points (c profiled on [0, 1.5])", ""]
    out.append(md(K, ["dataset", "npts", "c_K0", "sigma_K0", "c_K1", "c_K1_ci_set", "sigma_K1", "E_K1", "p_K1", "q_K1",
                      "alphaN_K1", "sigma_K1_c0", "sigma_K1_c1", "sigma_chin", "sigma_chin_c1", "c_chin"]))
    out += ["", "Second N term inside the Kaplan law (K2 vs K1):", ""]
    out.append(md(K, ["dataset", "c_K2", "c_K2_ci_set", "sigma_K2", "B_K2", "beta_K2", "z_wald_K2", "dbic_K1_K2",
                      "z_boot", "boot_frac_pos", "detect_primary", "shows_term", "ho_rmse_K1", "ho_rmse_K2",
                      "rev_mean_K1", "rev_mean_K2", "rev_pos_K1", "rev_pos_K2"]))
    out += ["", "B3 reverse ladder (fitted on the 7 sizes >= 100M; mean residual per smaller size):", ""]
    W = RK.pivot_table(index=["dataset", "N_total"], columns="model", values="resid").reset_index()
    out.append(md(W, list(W.columns)))
    open(os.path.join(RES, "dm3_summary.md"), "w").write("\n".join(out) + "\n")
    print("wrote dm3_summary.md")


if __name__ == "__main__":
    main()
